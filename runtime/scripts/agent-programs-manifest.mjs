// Writes src/infrastructure/agent-programs-manifest.ts from package-lock.json: for Claude Code and Codex, the exact
// per-platform npm package Saturn downloads on demand (version, tarball URL, sha512 integrity), plus its download
// size from the registry for the Settings button. Run it after updating either SDK; a test fails until you do.
//
//   node scripts/agent-programs-manifest.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const runtime = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(readFileSync(path.join(runtime, "package-lock.json"), "utf8")).packages;
const PROGRAMS = {
  "claude-code": /^node_modules\/@anthropic-ai\/claude-agent-sdk-(darwin|linux|win32)-(arm64|x64)$/,
  codex: /^node_modules\/@openai\/codex-(darwin|linux|win32)-(arm64|x64)$/,
};

const manifest = {};
for (const [program, pattern] of Object.entries(PROGRAMS)) {
  manifest[program] = {};
  for (const [key, entry] of Object.entries(lock)) {
    const match = pattern.exec(key);
    if (!match || !entry.resolved || !entry.integrity) continue;
    let size = 0;
    try {
      // The registry answers HEAD without a length; a one-byte range request reports the total in Content-Range.
      const response = await fetch(entry.resolved, { headers: { range: "bytes=0-0" } });
      size = Number(/\/(\d+)$/.exec(response.headers.get("content-range") ?? "")?.[1]) || 0;
      await response.body?.cancel();
    } catch {
      // Offline: the button just leaves the size out.
    }
    manifest[program][`${match[1]}-${match[2]}`] = { version: entry.version.replace(/-(darwin|linux|win32)-(arm64|x64)$/, ""), url: entry.resolved, integrity: entry.integrity, size };
  }
}

const body = `// Generated by scripts/agent-programs-manifest.mjs from package-lock.json. Do not edit by hand.
/** The npm package Saturn downloads for each program and platform, pinned to the lock file's integrity. */
export type ProgramPackage = { version: string; url: string; integrity: string; size: number };

export const AGENT_PROGRAM_PACKAGES: Record<"claude-code" | "codex", Record<string, ProgramPackage>> = ${JSON.stringify(manifest, null, 2)};
`;
writeFileSync(path.join(runtime, "src", "infrastructure", "agent-programs-manifest.ts"), body);
for (const [program, platforms] of Object.entries(manifest)) {
  console.log(`${program}: ${Object.entries(platforms).map(([platform, item]) => `${platform} ${(item.size / 1048576).toFixed(0)} MB`).join(", ")}`);
}
